const GIF_ABI = "arm64-v8a";

function image(
  api: string,
  tag: string,
  abi: string,
  extra: Partial<SystemImage> = {},
): SystemImage {
  const pkg = `system-images;android-${api};${tag};${abi}`;
  return {
    name: imageDisplayName(api, tag, abi),
    value: pkg,
    package: pkg,
    api,
    sysdir: `system-images/android-${api}/${tag}/${abi}`,
    ...extra,
  };
}

export interface DemoAvd {
  name: string;
  deviceName: string;
  sysdir: string;
  running: boolean;
}

export interface DemoIosDevice {
  name: string;
  value: string;
  runtime: string;
}

export type DemoImageSpec = ImageSpec;

export interface DemoProfile {
  name: string;
  value: string;
  supportedSdks: DemoImageSpec[];
}

export interface DemoCatalog {
  ios: MenuItem[];
  watchos: MenuItem[];
  android: MenuItem[];
  installed: Record<FormFactor, SystemImage[]>;
  available: Record<FormFactor, SystemImage[]>;
  profiles: Record<FormFactor, DemoProfile[]>;
}

export interface DemoWorld {
  ios: DemoIosDevice[];
  watchos: DemoIosDevice[];
  androidAvds: DemoAvd[];
  phoneImages: DemoImageSpec[];
  wearImages: DemoImageSpec[];
  installedImages: DemoImageSpec[];
  profiles: Record<FormFactor, DemoProfile[]>;
}

function cloneProfile(profile: DemoProfile): DemoProfile {
  return {
    name: profile.name,
    value: profile.value,
    supportedSdks: profile.supportedSdks.map((spec) => ({ ...spec })),
  };
}

export function createNewDeviceOption(): MenuItem {
  return {
    name: "Create new device",
    value: CREATE_VALUE,
    create: true,
    accent: "purple",
  };
}

function appleMenuItem(device: DemoIosDevice): MenuItem {
  return {
    name: appleDeviceLabel(device.name, device.runtime),
    value: device.value,
  };
}

export function specsFromAvds(avds: DemoAvd[]): DemoImageSpec[] {
  return uniqueSpecs(avds.map((avd) => specFromSysdir(avd.sysdir)).filter((spec): spec is DemoImageSpec => Boolean(spec)));
}

export function seedInstalledSpecs(): DemoImageSpec[] {
  return uniqueSpecs([...DEMO.installedImages, ...specsFromAvds(DEMO.androidAvds)]);
}

export function seedInstalledPackages(abi: string): string[] {
  return seedInstalledSpecs().map((spec) => specToPackage(spec, abi));
}

function imageFromSpec(spec: DemoImageSpec, abi: string, extra: Partial<SystemImage> = {}): SystemImage {
  return image(spec.api, spec.tag, abi, extra);
}

export function createDemoCatalog(): DemoCatalog {
  const installed = seedInstalledSpecs();
  const installedKeys = new Set(installed.map((spec) => `${spec.api};${spec.tag}`));
  const isInstalled = (spec: DemoImageSpec) => installedKeys.has(`${spec.api};${spec.tag}`);
  return {
    ios: DEMO.ios.map(appleMenuItem),
    watchos: DEMO.watchos.map(appleMenuItem),
    android: [
      ...DEMO.androidAvds.map((avd) => ({
        name: avd.name,
        value: avd.name,
        running: avd.running,
      })),
      createNewDeviceOption(),
    ],
    installed: {
      phone: installed.filter((spec) => !isWearSpec(spec)).map((spec) => imageFromSpec(spec, GIF_ABI)),
      wear: installed.filter(isWearSpec).map((spec) => imageFromSpec(spec, GIF_ABI)),
    },
    available: {
      phone: DEMO.phoneImages.map((spec) => imageFromSpec(spec, GIF_ABI, { installed: isInstalled(spec) })),
      wear: DEMO.wearImages.map((spec) => imageFromSpec(spec, GIF_ABI, { installed: isInstalled(spec) })),
    },
    profiles: {
      phone: DEMO.profiles.phone.map(cloneProfile),
      wear: DEMO.profiles.wear.map(cloneProfile),
    },
  };
}

export function demoProfiles(): DemoProfile[] {
  return [...DEMO.profiles.phone, ...DEMO.profiles.wear];
}

export function allDemoImageSpecs(): DemoImageSpec[] {
  return uniqueSpecs([...DEMO.phoneImages, ...DEMO.wearImages]);
}

